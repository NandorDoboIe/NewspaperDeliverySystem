package DeliveryDocket;

import java.time.LocalDate;
import java.time.format.DateTimeParseException;
import java.util.LinkedHashMap;

import Database.DataProvider;

public class DeliveryDocket implements DataProvider{

	private final int deliveryDocketId; // 0 means this record has not been inserted yet
	private int orderId;
	private int customerId;
	private String date; // yyyy-MM-dd
	private boolean success;
	
	// ID may be absent before insertion
	public DeliveryDocket(LinkedHashMap<String, Object> row) {
		 this(optionalId(row),
				 toInt(row.get("orderId")),
				 toInt(row.get("customerId")),
		         dateFromValue(row.get("date")),
		         toBoolean(row.get("success")));
	}
	
	public DeliveryDocket(int deliveryDocketId, int orderId, int customerId, String date, boolean success) {
		if(verifyId(deliveryDocketId)) {
			this.deliveryDocketId = deliveryDocketId;
		}
		else {
			throw new IllegalArgumentException("Invalid ID");
		}
		setOrderId(orderId);
		setCustomerId(customerId);
		setDate(date);
		setSuccess(success);
		
	}
	
	
	public int getDeliveryDocketId() {return this.deliveryDocketId;}
	
	public int getCustomerId() {return this.customerId;}
	
	public int getOrderId() {return this.orderId;}
	
	public String getDate() {return this.date;}
	
	public LocalDate getLocalDate() {return LocalDate.parse(this.date);}
	
	public boolean getSuccess() {return this.success;}
	
	
	public void setCustomerId(int customerId) {
		if(verifyForeignId(customerId)) {
			this.customerId = customerId;
		}
		else {
			throw new IllegalArgumentException("Invalid Customer ID");
		}
	}
	
	public void setOrderId(int orderId) {
		if(verifyForeignId(orderId)) {
			this.orderId = orderId;
		}
		else {
			throw new IllegalArgumentException("Invalid Order ID");
		}
	}
	
	public void setDate(String date) {
		if(verifyDate(date)) {
			this.date = date.trim();
		}
		else {
			throw new IllegalArgumentException("Invalid Date");
		}
	}
	
	public void setSuccess(boolean success) {
		this.success = success;
	}
	
	@Override
	public String toString() {
		return "Delivery Docket ID: " + deliveryDocketId + " | Order ID: " + orderId + " | Customer ID: "
				+ customerId + " | Date: " + date + " | Success: " + success;
	}
	
	
	private boolean verifyId(int id) {
		return id >= 0;
	}
	
	// order and customer ids are generated by MySQL, so they start at 1
	private boolean verifyForeignId(int id) {
		return id > 0;
	}
	
	// only real dates in yyyy-MM-dd format
	private boolean verifyDate(String date) {
		if(date == null) {
			return false;
		}
		try {
			LocalDate.parse(date.trim());
			return true;
		} catch (DateTimeParseException ex) {
			return false;
		}
	}
	
	// all fields are checked before any are changed
	public void updateDeliveryDocket(int orderId, int customerId, String date, boolean success){
		if(!verifyForeignId(orderId)) {
			throw new IllegalArgumentException("Invalid Order ID");
		}
		if(!verifyForeignId(customerId)) {
			throw new IllegalArgumentException("Invalid Customer ID");
		}
		if(!verifyDate(date)) {
			throw new IllegalArgumentException("Invalid Date");
		}
        setOrderId(orderId);
		setCustomerId(customerId);
		setDate(date);
		setSuccess(success);
    }
	
	
	public LinkedHashMap<String,Object> getData(){
		LinkedHashMap<String,Object> data = new LinkedHashMap<>();
		data.put("orderId", this.getOrderId());
		data.put("customerId",this.getCustomerId());
		data.put("date",this.getDate());
		data.put("success",this.getSuccess());
		return data;
	}
	
	private static int optionalId(LinkedHashMap<String, Object> row) {
		return row.containsKey("deliveryDocketId") ? toInt(row.get("deliveryDocketId")) : 0;
	}
	
	// MySQL returns a java.sql.Date, the CLI supplies a String
	private static String dateFromValue(Object value) {
		if (value == null) {
			throw new IllegalArgumentException("Invalid Date");
		}
		return String.valueOf(value).trim();
	}
	
	// MySQL returns a Boolean or 0/1, the CLI supplies a String
	private static boolean toBoolean(Object value) {
		if (value instanceof Boolean) {
			return (Boolean) value;
		}
		if (value instanceof Number) {
			return ((Number) value).intValue() != 0;
		}
		String text = String.valueOf(value).trim().toLowerCase();
		if (text.equals("true") || text.equals("yes") || text.equals("1")) {
			return true;
		}
		if (text.equals("false") || text.equals("no") || text.equals("0")) {
			return false;
		}
		throw new IllegalArgumentException("Invalid success: " + value);
	}
	
	private static int toInt(Object value) {
	    if (value instanceof Number) {
	      return ((Number) value).intValue();
	    }
	    try {
	      return Integer.parseInt(String.valueOf(value).trim());
	    } catch (NumberFormatException ex) {
	      throw new IllegalArgumentException("Invalid number: " + value);
	    }
	}

}
